#!/usr/bin/env node

/*
 * Build the app's book-to-cover map from Open Library's public search API.
 *
 * Usage:
 *   node scripts/sync-openlibrary-covers.cjs          # report matches only
 *   node scripts/sync-openlibrary-covers.cjs --write  # update js/covers.js
 */

const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const ROOT = path.resolve(__dirname, "..");
const AUTHOR_KEYS = {
  "David Walliams": "OL2623989A",
  "Roald Dahl": "OL34184A",
};

/* Title variants in the Open Library catalog, keyed by book id. */
const TITLE_OVERRIDES = {
  b17: "Astro Chimp",
  b20: "World's Worst Children 2",
  b23: "World's Worst Parents",
  b32: "Bear Who Went Boo!",
  b36: "Creature Choir",
  b39: "Marmalade - the Orange Panda",
  b58: "Boy",
};

/* Manual covers for books Open Library can't match, keyed by book id. */
const PUBLISHER_FALLBACKS = {
  // Astro Chimp isn't linked to the Walliams author key, but has an OL cover.
  b17: {
    image: "https://covers.openlibrary.org/b/id/15154258-L.jpg",
    page: "https://openlibrary.org/works/OL37831873W",
    source: "Open Library",
  },
  // Work-level covers are French/Polish editions; pin English edition covers.
  b19: {
    image: "https://covers.openlibrary.org/b/id/12689068-L.jpg",
    page: "https://openlibrary.org/works/OL20065223W",
    source: "Open Library",
  },
  b20: {
    image: "covers/worstchildren2.jpg",
    page: "https://openlibrary.org/works/OL21133235W",
    source: "Publisher",
  },
  // No cover art on Open Library yet; official covers stored in covers/.
  b25: {
    image: "covers/b25.jpg",
    page: "https://openlibrary.org/works/OL35712349W",
    source: "Publisher",
  },
  b26: {
    image: "covers/b26.jpg",
    page: "https://openlibrary.org/works/OL42541252W",
    source: "Publisher",
  },
};

/* Book ids that should always use the publisher fallback. */
const PUBLISHER_OVERRIDE_IDS = new Set(["b19", "b20", "b25", "b26"]);

function loadBooks() {
  const filename = path.join(ROOT, "js", "data.js");
  const source = `${fs.readFileSync(filename, "utf8")}\n;globalThis.__BOOKS = BOOKS;`;
  const context = {};
  vm.createContext(context);
  vm.runInContext(source, context, { filename });
  return context.__BOOKS;
}

function normalizeTitle(title) {
  return title
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/\bspecial edition\b/g, " ")
    .replace(/\bbook\s*\d+\b/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function similarity(left, right) {
  const a = new Set(normalizeTitle(left).split(" ").filter(Boolean));
  const b = new Set(normalizeTitle(right).split(" ").filter(Boolean));
  const intersection = [...a].filter(token => b.has(token)).length;
  const dice = (2 * intersection) / (a.size + b.size || 1);
  const [firstA] = a;
  const [firstB] = b;
  return dice + (firstA === firstB ? 0.08 : 0);
}

function chooseMatch(book, candidates) {
  const wanted = TITLE_OVERRIDES[book.id] || book.title;
  const normalized = normalizeTitle(wanted);
  const exact = candidates.filter(item => normalizeTitle(item.title) === normalized);
  if (exact.length) return { item: exact[0], method: "exact", score: 1 };

  const ranked = candidates
    .map(item => ({ item, score: similarity(wanted, item.title) }))
    .sort((a, b) => b.score - a.score);
  const best = ranked[0];
  const gap = best ? best.score - (ranked[1]?.score || 0) : 0;
  if (best && best.score >= 0.9 && gap >= 0.08) {
    return { ...best, method: "fuzzy" };
  }
  return { item: null, method: "unmatched", score: best?.score || 0, suggestions: ranked.slice(0, 3) };
}

function renderCoverMap(matches) {
  const lines = [
    "/* Generated by scripts/sync-openlibrary-covers.cjs. */",
    "/* Cover images and work links are provided by Open Library. */",
    "const BOOK_COVERS = {",
  ];

  for (const { book, match } of matches) {
    if (!match.item) continue;
    let cover;
    if (match.item.cover_i) {
      cover = {
        image: `https://covers.openlibrary.org/b/id/${match.item.cover_i}-L.jpg`,
        page: `https://openlibrary.org${match.item.key}`,
        source: "Open Library",
      };
    } else {
      cover = match.item;
    }
    lines.push(`  ${JSON.stringify(book.id)}: ${JSON.stringify(cover)},`);
  }

  lines.push("};", "");
  return lines.join("\n");
}

async function fetchCandidates(authorKey) {
  const url = new URL("https://openlibrary.org/search.json");
  url.searchParams.set("q", `author_key:${authorKey}`);
  url.searchParams.set("limit", "1000");
  url.searchParams.set("fields", "key,title,cover_i");
  const response = await fetch(url, {
    headers: { "User-Agent": "JessicasBookshelf/1.0 (personal reading tracker)" },
  });
  if (!response.ok) throw new Error(`Open Library returned ${response.status} for ${authorKey}`);
  const payload = await response.json();
  return {
    numFound: payload.numFound,
    candidates: payload.docs.filter(item => item.cover_i && item.key && item.title),
  };
}

async function main() {
  const candidatesByAuthor = {};
  for (const [author, key] of Object.entries(AUTHOR_KEYS)) {
    const { numFound, candidates } = await fetchCandidates(key);
    candidatesByAuthor[author] = candidates;
    console.log(`${author}: ${numFound} works; with covers: ${candidates.length}`);
  }

  const books = loadBooks();
  const matches = books.map(book => {
    const candidates = candidatesByAuthor[book.author] || [];
    if (PUBLISHER_OVERRIDE_IDS.has(book.id)) {
      return { book, match: { item: PUBLISHER_FALLBACKS[book.id], method: "publisher", score: 1 } };
    }
    const match = chooseMatch(book, candidates);
    if (!match.item && PUBLISHER_FALLBACKS[book.id]) {
      return { book, match: { item: PUBLISHER_FALLBACKS[book.id], method: "publisher", score: 1 } };
    }
    return { book, match };
  });
  const exact = matches.filter(({ match }) => match.method === "exact");
  const fuzzy = matches.filter(({ match }) => match.method === "fuzzy");
  const publisher = matches.filter(({ match }) => match.method === "publisher");
  const unmatched = matches.filter(({ match }) => !match.item);

  console.log(`App books: ${books.length}; Open Library: ${exact.length + fuzzy.length}; publisher fallback: ${publisher.length}; unmatched: ${unmatched.length}`);

  if (fuzzy.length) {
    console.log("\nFuzzy matches:");
    for (const { book, match } of fuzzy) {
      console.log(`  ${book.id}: ${book.title} -> ${match.item.title} (${match.score.toFixed(2)})`);
    }
  }

  if (unmatched.length) {
    console.log("\nUnmatched books (closest candidates):");
    for (const { book, match } of unmatched) {
      const suggestions = match.suggestions
        .map(({ item, score }) => `${item.title} [${score.toFixed(2)}]`)
        .join(" | ");
      console.log(`  ${book.id}: ${book.title} -> ${suggestions}`);
    }
  }

  if (process.argv.includes("--write")) {
    const destination = path.join(ROOT, "js", "covers.js");
    fs.writeFileSync(destination, renderCoverMap(matches), "utf8");
    console.log(`\nWrote ${matches.length - unmatched.length} cover mappings to ${path.relative(ROOT, destination)}.`);
  }
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
